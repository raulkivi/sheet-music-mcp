"""The built wheel ships the Score Viewer (decision D1, spike step 9, DoD-6).

The HTML is generated by ``ui/`` and gitignored, so hatch only packages it through its
``artifacts`` setting. Run after a UI build::

    cd ui && npm run build && npm run copy-assets
    cd ../render-mcp && VIRTUAL_ENV= .venv/bin/pytest tests/test_packaging.py -m integration
"""

import re
import shutil
import subprocess
import zipfile
from pathlib import Path

import pytest

pytestmark = pytest.mark.integration

PROJECT = Path(__file__).parents[1]
ASSET = "render_mcp/ui/assets/score-viewer.html"
BUILT_ASSET = PROJECT / "src" / ASSET

# Script and style bodies are code, not markup (same rule as ui/scripts/check-html.mjs).
_RAW_TEXT = re.compile(r"<(script|style)\b([^>]*)>.*?</\1\s*>", re.IGNORECASE | re.DOTALL)
_REFERENCE = re.compile(
    r"<(script|link|img|iframe|source|audio|video)\b[^>]*?\s(src|href)\s*=\s*[\"']?([^\"'\s>]*)",
    re.IGNORECASE,
)


def off_origin_references(html: str) -> list[str]:
    """Elements loading anything not inside the document (AC-R1: no CSP allowances needed)."""
    markup = _RAW_TEXT.sub(lambda m: f"<{m.group(1)}{m.group(2)}>", html)
    return [
        f"<{tag} {attr}={value}>"
        for tag, attr, value in _REFERENCE.findall(markup)
        if not (value.startswith("#") or value.lower().startswith("data:"))
    ]


def test_reference_check_finds_external_scripts_and_styles():
    html = (
        '<script>const s = "<script src=https://x.test/a.js>";</script>'
        '<script src="https://cdn.test/app.js"></script>'
        '<link rel="stylesheet" href="/style.css"><img src="data:image/png;base64,AA">'
    )

    assert off_origin_references(html) == [
        "<script src=https://cdn.test/app.js>",
        "<link href=/style.css>",
    ]


@pytest.fixture(scope="module")
def wheel(tmp_path_factory) -> Path:
    if not BUILT_ASSET.is_file():
        pytest.skip(f"{ASSET} is not built: run `npm run build && npm run copy-assets` in ui/")
    if shutil.which("uv") is None:
        pytest.skip("uv is not on PATH")
    out = tmp_path_factory.mktemp("dist")
    subprocess.run(
        ["uv", "build", "--wheel", "--out-dir", str(out), str(PROJECT)],
        check=True,
        capture_output=True,
        text=True,
    )
    [built] = out.glob("render_mcp-*.whl")
    return built


def test_wheel_contains_the_score_viewer(wheel):
    with zipfile.ZipFile(wheel) as archive:
        assert ASSET in archive.namelist()
        assert archive.read(ASSET) == BUILT_ASSET.read_bytes()


def test_packaged_html_loads_nothing_off_origin(wheel):
    with zipfile.ZipFile(wheel) as archive:
        html = archive.read(ASSET).decode("utf-8")

    assert html.lstrip().lower().startswith("<!doctype html")
    assert off_origin_references(html) == []
